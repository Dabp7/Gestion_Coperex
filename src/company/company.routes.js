import { Router } from 'express';
import { createCompany, listCompanies, getCompanyTrayectory, getCompanyCategory, getCompaniesAsc, getCompaniesDesc, updateCompany, generateCompanyReport } from './company.controller.js';
import { validateJWT, requireAdmin } from '../middlewares/validate-jwt.js';
const router = Router();
router.use(validateJWT, requireAdmin);
router.get('/', listCompanies);
router.post('/addCompany', createCompany);
router.get('/getTrayectory/:trayectoryGet', getCompanyTrayectory);
router.get('/getCategory/:category', getCompanyCategory);
router.get('/getCompany/A-Z', getCompaniesAsc);
router.get('/getCompany/Z-A', getCompaniesDesc);
router.put('/editCompany/:idCompany', updateCompany);
router.get('/report', generateCompanyReport);
export default router;
